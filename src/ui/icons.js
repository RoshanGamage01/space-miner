const cache = new Map();

function lighten(hex, f) {
  const n = parseInt(hex.slice(1), 16);
  const ch = (v) => Math.round(v + (255 - v) * f);
  return `rgb(${ch((n >> 16) & 255)},${ch((n >> 8) & 255)},${ch(n & 255)})`;
}
function darken(hex, f) {
  const n = parseInt(hex.slice(1), 16);
  const ch = (v) => Math.round(v * (1 - f));
  return `rgb(${ch((n >> 16) & 255)},${ch((n >> 8) & 255)},${ch(n & 255)})`;
}

export function icon(name, color = '#5ef1ff', size = 16) {
  const key = `${name}|${color}|${size}`;
  if (cache.has(key)) return cache.get(key);
  const map = ICONS[name] || ICONS.ore;
  const cols = { '#': color, '+': lighten(color, 0.55), o: darken(color, 0.45), c: '#5ef1ff' };
  let rects = '';
  map.forEach((row, y) => {
    for (let x = 0; x < 8; x++) {
      const c = cols[row[x]];
      if (c) rects += `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${c}"/>`;
    }
  });
  const svg = `<svg class="px" width="${size}" height="${size}" viewBox="0 0 8 8" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
  cache.set(key, svg);
  return svg;
}
